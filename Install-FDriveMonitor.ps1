#requires -Version 5.1
<#
.SYNOPSIS
    安装 / 卸载 F 盘监控。

.DESCRIPTION
    两种安装方式：
      -Method Task     （默认，推荐）注册计划任务：登录时运行 + 之后每 N 分钟检查一次。
                      需要管理员权限。
      -Method Startup  （免管理员）在“启动”文件夹放一个 VBS，登录后隐藏运行常驻循环。

.EXAMPLE
    # 管理员 PowerShell 中执行（推荐）
    .\Install-FDriveMonitor.ps1

.EXAMPLE
    # 没有管理员权限时
    .\Install-FDriveMonitor.ps1 -Method Startup

.EXAMPLE
    # 卸载
    .\Install-FDriveMonitor.ps1 -Uninstall
#>
[CmdletBinding()]
param(
    [ValidateSet('Task', 'Startup')]
    [string]$Method = 'Task',
    [switch]$Uninstall,
    [int]$IntervalMinutes = 2,
    [string]$Drive = 'F'
)

$ErrorActionPreference = 'Stop'

$root = $PSScriptRoot
$monitor = Join-Path $root 'FDriveMonitor.ps1'
$alertScript = Join-Path $root 'Show-FDriveAlert.ps1'
$taskName = 'F Drive Health Monitor'
$psExe = Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe'
$startupDir = [Environment]::GetFolderPath('Startup')
$startupVbs = Join-Path $startupDir 'FDriveMonitor.vbs'

function Test-IsAdmin {
    $id = [Security.Principal.WindowsIdentity]::GetCurrent()
    $p = New-Object Security.Principal.WindowsPrincipal($id)
    return $p.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
}

function Stop-RunningWatchers {
    try {
        Get-CimInstance Win32_Process -Filter "Name='powershell.exe'" -ErrorAction SilentlyContinue |
            Where-Object { $_.CommandLine -and $_.CommandLine -like '*FDriveMonitor.ps1*' } |
            ForEach-Object { Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue }
    }
    catch { }
}

if (-not (Test-Path -LiteralPath $monitor)) { throw "找不到主脚本：$monitor" }
if (-not (Test-Path -LiteralPath $alertScript)) { throw "找不到提醒窗口脚本：$alertScript" }

# ------------------------------------------------------------------ 卸载
if ($Uninstall) {
    $removed = $false

    $task = Get-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue
    if ($task) {
        try { Stop-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue } catch { }
        try {
            Unregister-ScheduledTask -TaskName $taskName -Confirm:$false -ErrorAction Stop
            Write-Host "已删除计划任务：$taskName" -ForegroundColor Green
            $removed = $true
        }
        catch { Write-Host "删除计划任务失败（请用管理员运行）：$($_.Exception.Message)" -ForegroundColor Yellow }
    }

    if (Test-Path -LiteralPath $startupVbs) {
        try {
            Remove-Item -LiteralPath $startupVbs -Force -ErrorAction Stop
            Write-Host "已删除启动项：$startupVbs" -ForegroundColor Green
            $removed = $true
        }
        catch { Write-Host "删除启动项失败：$($_.Exception.Message)" -ForegroundColor Yellow }
    }

    Stop-RunningWatchers
    if (-not $removed) { Write-Host '没有找到已安装的任务或启动项。' -ForegroundColor Yellow }
    return
}

# ------------------------------------------------------------------ 安装
if ($Method -eq 'Task') {
    if (-not (Test-IsAdmin)) {
        throw '注册计划任务需要管理员权限：请右键 Windows PowerShell / 终端 → 以管理员身份运行，再执行本脚本；或改用：.\Install-FDriveMonitor.ps1 -Method Startup'
    }

    # 生成静默启动器：wscript 本身没有控制台，避免每 2 分钟闪一下黑框
    # 注意：启动器按自身所在目录解析脚本路径，不含绝对路径，可直接提交到仓库
    $launcher = Join-Path $root 'Run-Monitor.vbs'
    $vbs = @"
' Silent launcher: runs FDriveMonitor.ps1 from the same folder, no console window.
' Generated by Install-FDriveMonitor.ps1; contains no absolute paths.
Set fso = CreateObject("Scripting.FileSystemObject")
Set sh  = CreateObject("WScript.Shell")
scriptPath = fso.BuildPath(fso.GetParentFolderName(WScript.ScriptFullName), "FDriveMonitor.ps1")
sh.Run "powershell.exe -NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File """ & scriptPath & """ -Drive $Drive", 0, False
"@
    Set-Content -LiteralPath $launcher -Value $vbs -Encoding ASCII

    $action = New-ScheduledTaskAction -Execute (Join-Path $env:SystemRoot 'System32\wscript.exe') `
        -Argument "`"$launcher`"" -WorkingDirectory $root

    $tLogon = New-ScheduledTaskTrigger -AtLogOn -User "$env:USERDOMAIN\$env:USERNAME"
    try { $tLogon.Delay = 'PT30S' } catch { }

    $tRepeat = New-ScheduledTaskTrigger -Once -At (Get-Date).AddMinutes(1) `
        -RepetitionInterval (New-TimeSpan -Minutes $IntervalMinutes) `
        -RepetitionDuration (New-TimeSpan -Days 3650)

    $settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `
        -StartWhenAvailable -MultipleInstances IgnoreNew -ExecutionTimeLimit (New-TimeSpan -Minutes 15)

    $principal = New-ScheduledTaskPrincipal -UserId "$env:USERDOMAIN\$env:USERNAME" `
        -LogonType Interactive -RunLevel Highest

    Register-ScheduledTask -TaskName $taskName -Action $action -Trigger @($tLogon, $tRepeat) `
        -Settings $settings -Principal $principal -Force `
        -Description "监控 NTFS 事件 50/140，$($Drive): 盘写入异常时弹窗提醒" | Out-Null

    Write-Host "已注册计划任务：$taskName" -ForegroundColor Green
    Write-Host ("  触发器：登录后 30 秒 + 每 {0} 分钟一次" -f $IntervalMinutes)
    Write-Host "  动作  ：wscript.exe `"$launcher`"（静默，无窗口）"
    Write-Host '  正在执行一次基线检查……'
    try { Start-ScheduledTask -TaskName $taskName -ErrorAction Stop; Start-Sleep -Seconds 3 } catch { }
}
else {
    # Startup 方式：登录后隐藏运行常驻循环，无需管理员
    $vbs = @"
' 由 Install-FDriveMonitor.ps1 生成，删除本文件即可取消开机自启
Set sh = CreateObject("WScript.Shell")
sh.Run "powershell.exe -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File ""$monitor"" -Drive $Drive -Watch", 0, False
"@
    Set-Content -LiteralPath $startupVbs -Value $vbs -Encoding ASCII
    Write-Host "已创建启动项：$startupVbs" -ForegroundColor Green
    Write-Host '  下次登录 Windows 时会隐藏启动常驻监控（每 30 秒检查一次）。'
    Write-Host '  现在先手动启动一次……'
    Start-Process -FilePath 'powershell.exe' -WindowStyle Hidden `
        -ArgumentList "-NoProfile -ExecutionPolicy Bypass -File `"$monitor`" -Drive $Drive" | Out-Null
}

Write-Host ''
Write-Host '常用命令：' -ForegroundColor Cyan
Write-Host "  查看报告：powershell -ExecutionPolicy Bypass -File `"$monitor`" -Summary"
Write-Host "  演示提醒：powershell -ExecutionPolicy Bypass -File `"$monitor`" -Force"
Write-Host "  卸载    ：powershell -ExecutionPolicy Bypass -File `"$PSScriptRoot\Install-FDriveMonitor.ps1`" -Uninstall"
Write-Host "  日志    ：$root\FDriveMonitor.log"
